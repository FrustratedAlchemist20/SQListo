# xyz2db/parsing.py

# XYZ file parsing for xyz2db
# This module provides functions to parse XYZ files,
# including multi-frame XYZ files, and extract relevant

import os
import re

import numpy as np

from .chemistry import SYMBOL_TO_Z
from .config import DEFAULT_CHARGE, DEFAULT_SPINMULT, MD_INPUT_COMMENT_PREFIX
from .energy_utils import compute_terachem_energy_fields


def extract_frame_number(comment: str):
    """
    Extract frame number from lines like:
      -1698.99738 frame 9004   xyz file generated by terachem
    """
    m = re.search(r"(?i)\bframe\s+(\d+)\b", comment)
    if m:
        try:
            return int(m.group(1))
        except ValueError:
            return None
    return None


def extract_energy(comment: str):
    """
    Supported formats:
      E=-123.456
      energy = -123.456
      Energy: -123.456
      -1698.99738 frame 9004   xyz file generated by terachem
    """
    patterns = [
        r"(?i)\bE(?:nergy)?\s*[:=]\s*([-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)",
        r"(?i)\bEtot\s*[:=]\s*([-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)",
        r"^\s*([-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)\b",
    ]
    for pat in patterns:
        m = re.search(pat, comment)
        if m:
            try:
                return float(m.group(1))
            except ValueError:
                return None
    return None


def _parse_thermostat_value(value: str):
    """
    TeraChem inputs often use something like:
      thermostat 300
    but may occasionally contain non-numeric text.
    """
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def parse_md_input(input_path: str, natoms=None, energy_label=None):
    data = {
        "input_filename": os.path.basename(input_path),
        "basis": None,
        "has_basis": 0,
        "coordinates_file": None,
        "charge": DEFAULT_CHARGE,
        "spinmult": DEFAULT_SPINMULT,
        "method": None,
        "dispersion": None,
        "has_dispersion": 0,
        "run_type": None,
        "nstep": None,
        "timestep": None,
        "thermostat": None,
        "rescalefreq": None,
        "tinit": None,
        "t0": None,
        "gpus": None,
        "raw_input_text": None,
        # Extra metadata for derived energetic quantities
        "natoms": natoms,
        "energy_label_from_input": energy_label,
        "energy_label_factor": None,
        "energy_temperature_K": None,
        "energy_kcal_mol": None,
        "zpe_kcal_mol": None,
        "dof": None,
    }

    with open(input_path, "r", encoding="utf-8", errors="replace") as f:
        raw_text = f.read()

    data["raw_input_text"] = raw_text

    for raw_line in raw_text.splitlines():
        line = raw_line.strip()

        if not line or line.startswith(MD_INPUT_COMMENT_PREFIX):
            continue

        parts = line.split(None, 1)
        key = parts[0].lower()
        value = parts[1].strip() if len(parts) > 1 else ""

        if key == "basis":
            data["basis"] = value
            data["has_basis"] = 1 if value else 0

        elif key == "coordinates":
            data["coordinates_file"] = value

        elif key == "charge":
            try:
                data["charge"] = int(value)
            except ValueError:
                data["charge"] = DEFAULT_CHARGE

        elif key in ("spinmult", "multiplicity"):
            try:
                value_int = int(value)
                data["spinmult"] = max(1, value_int)
            except ValueError:
                data["spinmult"] = DEFAULT_SPINMULT

        elif key == "method":
            data["method"] = value

        elif key == "dispersion":
            data["dispersion"] = value
            data["has_dispersion"] = 1 if value.lower() not in ("", "no", "none", "false", "0") else 0

        elif key == "run":
            data["run_type"] = value

        elif key == "nstep":
            try:
                data["nstep"] = int(value)
            except ValueError:
                data["nstep"] = None

        elif key == "timestep":
            try:
                data["timestep"] = float(value)
            except ValueError:
                data["timestep"] = None

        elif key == "thermostat":
            # Keep thermostat as numeric K when possible
            thermostat_val = _parse_thermostat_value(value)
            data["thermostat"] = thermostat_val if thermostat_val is not None else value

        elif key == "rescalefreq":
            try:
                data["rescalefreq"] = int(value)
            except ValueError:
                data["rescalefreq"] = None

        elif key == "tinit":
            try:
                data["tinit"] = float(value)
            except ValueError:
                data["tinit"] = None

        elif key == "t0":
            try:
                data["t0"] = float(value)
            except ValueError:
                data["t0"] = None

        elif key == "gpus":
            try:
                data["gpus"] = int(value)
            except ValueError:
                data["gpus"] = None

    # Derived energy fields for TeraChem.
    # Use the actual MD temperature in this priority:
    #   1) tinit
    #   2) t0
    #   3) thermostat only if it is numeric
    #
    # Formula:
    #   T = 2 * ZPE * f / (s * kB)
    # therefore:
    #   energy_kcal_mol = ZPE * f = T * s * kB / 2

    temperature_K = None

    if isinstance(data["tinit"], (int, float)):
        temperature_K = data["tinit"]
    elif isinstance(data["t0"], (int, float)):
        temperature_K = data["t0"]
    elif isinstance(data["thermostat"], (int, float)):
        temperature_K = data["thermostat"]

    energy_fields = compute_terachem_energy_fields(
        thermostat_K=temperature_K,
        natoms=data["natoms"],
        energy_label=data["energy_label_from_input"],
    )

    data.update(energy_fields)

    return data


def parse_xyz_multiframe(filepath: str):
    """
    Returns:
      natoms: int
      symbols: list[str]
      frames_coords: np.ndarray shape (nframes, natoms, 3)
      comments: list[str]
      energies: list[float|None]
    """
    frames_coords = []
    comments = []
    energies = []
    symbols_ref = None
    natoms_ref = None

    with open(filepath, "r", encoding="utf-8", errors="replace") as f:
        lines = f.readlines()

    i = 0
    frame_idx = 0
    nlines = len(lines)

    while i < nlines:
        line = lines[i].strip()
        if not line:
            i += 1
            continue

        try:
            natoms = int(line)
        except ValueError as exc:
            raise ValueError(
                f"Invalid XYZ format at line {i+1}: expected number of atoms."
            ) from exc

        if i + 1 >= nlines:
            raise ValueError(f"Incomplete frame at line {i+1}: missing comment line.")

        comment = lines[i + 1].rstrip("\n")
        energies.append(extract_energy(comment))
        comments.append(comment)

        block_start = i + 2
        block_end = block_start + natoms
        if block_end > nlines:
            raise ValueError(f"Incomplete frame at frame {frame_idx}: missing atomic lines.")

        frame_symbols = []
        frame_coords = np.zeros((natoms, 3), dtype=np.float32)

        for j, raw in enumerate(lines[block_start:block_end]):
            parts = raw.split()
            if len(parts) < 4:
                raise ValueError(
                    f"Invalid atomic line in frame {frame_idx}, line {block_start + j + 1}."
                )
            sym = parts[0]
            if sym not in SYMBOL_TO_Z:
                raise ValueError(f"Unknown atomic symbol: '{sym}'")
            try:
                x, y, z = map(float, parts[1:4])
            except ValueError as exc:
                raise ValueError(
                    f"Invalid coordinates in frame {frame_idx}, line {block_start + j + 1}."
                ) from exc

            frame_symbols.append(sym)
            frame_coords[j] = [x, y, z]

        if natoms_ref is None:
            natoms_ref = natoms
            symbols_ref = frame_symbols
        else:
            if natoms != natoms_ref:
                raise ValueError(
                    f"The number of atoms changes between frames: {natoms_ref} vs {natoms}"
                )
            if frame_symbols != symbols_ref:
                raise ValueError(
                    "The atomic order or identity changes between frames. "
                    "This script assumes fixed topology/atomic ordering."
                )

        frames_coords.append(frame_coords)
        i = block_end
        frame_idx += 1

    if natoms_ref is None or not frames_coords:
        raise ValueError("No valid frames were found in the XYZ file.")

    frames_coords = np.stack(frames_coords, axis=0)
    return natoms_ref, symbols_ref, frames_coords, comments, energies