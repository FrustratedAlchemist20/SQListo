def list_trajectories(db_path: str):
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()
    cur.execute(
        """
        SELECT
            t.traj_uid,
            t.traj_code,
            t.molecule,
            t.isomer,
            t.method_label,
            t.energy_label,
            t.run_id,
            t.natoms,
            t.nframes,
            t.created_at,
            t.source_filename,
            m.input_filename
        FROM trajectories t
        LEFT JOIN md_inputs m ON t.input_id = m.input_id
        ORDER BY t.created_at DESC
        """
    )
    rows = cur.fetchall()
    conn.close()

    if not rows:
        print("La base de datos no contiene trayectorias.")
        return

    print(f"{'traj_uid':26s} {'traj_code':22s} {'frames':>8s} {'input':12s} archivo")
    print("-" * 110)
    for row in rows:
        traj_uid, traj_code, molecule, isomer, method_label, energy_label, run_id, natoms, nframes, created_at, source_filename, input_filename = row
        print(f"{traj_uid:26s} {str(traj_code):22s} {nframes:8d} {str(input_filename):12s} {source_filename}")

def restore_all_from_db(db_path: str, output_dir: str):
    os.makedirs(output_dir, exist_ok=True)

    output_input = restore_single_input_file_from_db(db_path, output_dir)
    if output_input is not None:
        print(f"Restored shared input -> {output_input}")
    else:
        print("No shared input file found in the database.")

    conn = sqlite3.connect(db_path)
    cur = conn.cursor()
    cur.execute("""
        SELECT traj_uid, source_filename
        FROM trajectories
        ORDER BY created_at, traj_uid
    """)
    rows = cur.fetchall()
    conn.close()

    if not rows:
        print("No trajectories found in the database.")
        return

    for i, (traj_uid, source_filename) in enumerate(rows, start=1):
        run_dir = os.path.join(output_dir, f"run_{i:03d}")
        os.makedirs(run_dir, exist_ok=True)

        xyz_name = source_filename if source_filename else "coors.xyz"
        output_xyz = os.path.join(run_dir, xyz_name)

        print(f"Restoring {traj_uid} -> {output_xyz}")
        restore_xyz_from_db(db_path, traj_uid, output_xyz)

        output_csv = os.path.join(run_dir, "frame_data.csv")
        export_frame_data_csv(db_path, traj_uid, output_csv)
        print(f"Restored frame data -> {output_csv}")

    print(f"Done. Restored {len(rows)} trajectory file(s) into: {os.path.abspath(output_dir)}")

