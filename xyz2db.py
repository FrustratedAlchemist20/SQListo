def restore_single_input_file_from_db(db_path: str, output_dir: str):
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    cur.execute(
        """
        SELECT input_filename, raw_input_text
        FROM md_inputs
        ORDER BY created_at, input_id
        LIMIT 1
        """
    )
    row = cur.fetchone()
    conn.close()

    if row is None:
        return None

    input_filename, raw_input_text = row

    if not input_filename or raw_input_text is None:
        return None

    os.makedirs(output_dir, exist_ok=True)
    output_input = os.path.join(output_dir, input_filename)

    with open(output_input, "w", encoding="utf-8") as f:
        f.write(raw_input_text)

    return output_input


def restore_xyz_from_db(db_path: str, traj_uid: str, output_xyz: str):
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    cur.execute(
        """
        SELECT natoms, atomic_numbers, symbols_json, nframes
        FROM trajectories
        WHERE traj_uid = ?
        """,
        (traj_uid,)
    )
    row = cur.fetchone()
    if row is None:
        conn.close()
        raise ValueError(f"No existe traj_uid='{traj_uid}' en la base.")

    natoms, atomic_numbers_blob, symbols_json, nframes = row
    atomic_numbers = np.frombuffer(atomic_numbers_blob, dtype=np.uint8)
    symbols = json.loads(symbols_json)

    if len(symbols) != natoms or len(atomic_numbers) != natoms:
        conn.close()
        raise ValueError("Inconsistencia en la información atómica almacenada.")

    cur.execute(
        """
        SELECT block_index, start_frame, end_frame, payload
        FROM frame_blocks
        WHERE traj_uid = ?
        ORDER BY block_index
        """,
        (traj_uid,)
    )
    blocks = cur.fetchall()
    conn.close()

    recovered_frames = 0
    with open(output_xyz, "w", encoding="utf-8") as out:
        for block_index, start_frame, end_frame, payload in blocks:
            coords_block, comments_block, energies_block = deserialize_block(payload)

            expected_n = end_frame - start_frame + 1
            if coords_block.shape[0] != expected_n:
                raise ValueError(
                    f"Bloque {block_index} corrupto: número de frames inesperado."
                )

            for iframe in range(coords_block.shape[0]):
                out.write(f"{natoms}\n")
                comment = comments_block[iframe] if comments_block[iframe] is not None else ""
                out.write(f"{comment}\n")
                coords = coords_block[iframe]
                for sym, (x, y, z) in zip(symbols, coords):
                    out.write(f"{sym:<2s} {x: .8f} {y: .8f} {z: .8f}\n")
                recovered_frames += 1

    print(f"Recuperación completada.")
    print(f"traj_uid     : {traj_uid}")
    print(f"frames       : {recovered_frames}")
    print(f"salida xyz   : {os.path.abspath(output_xyz)}")

def export_frame_data_csv(db_path: str, traj_uid: str, output_csv: str):
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    # Get timestep from md_inputs through trajectories
    cur.execute(
        """
        SELECT m.timestep
        FROM trajectories t
        LEFT JOIN md_inputs m ON t.input_id = m.input_id
        WHERE t.traj_uid = ?
        """,
        (traj_uid,)
    )
    row = cur.fetchone()
    timestep_fs = row[0] if row and row[0] is not None else None

    cur.execute(
        """
        SELECT block_index, payload
        FROM frame_blocks
        WHERE traj_uid = ?
        ORDER BY block_index
        """,
        (traj_uid,)
    )
    blocks = cur.fetchall()
    conn.close()

    if not blocks:
        raise ValueError(f"No frame blocks found for traj_uid='{traj_uid}'")

    os.makedirs(os.path.dirname(output_csv), exist_ok=True)

    frame_idx_global = 0
    with open(output_csv, "w", encoding="utf-8") as f:
        f.write("frame_idx,frame_number,energy,time_ps\n")

        for block_index, payload in blocks:
            coords_block, comments_block, energies_block = deserialize_block(payload)

            for comment, energy in zip(comments_block, energies_block):
                frame_number = extract_frame_number(comment)
                time_ps = ""

                if frame_number is not None and timestep_fs is not None:
                    time_ps = frame_number * float(timestep_fs) / 1000.0

                energy_str = "" if energy is None else f"{energy:.10f}"
                time_str = "" if time_ps == "" else f"{time_ps:.10f}"

                f.write(f"{frame_idx_global},{'' if frame_number is None else frame_number},{energy_str},{time_str}\n")
                frame_idx_global += 1

def export_frame_data_csv(db_path: str, traj_uid: str, output_csv: str):
    conn = sqlite3.connect(db_path)
    cur = conn.cursor()

    cur.execute(
        """
        SELECT m.timestep
        FROM trajectories t
        LEFT JOIN md_inputs m ON t.input_id = m.input_id
        WHERE t.traj_uid = ?
        """,
        (traj_uid,)
    )
    row = cur.fetchone()
    timestep_fs = row[0] if row and row[0] is not None else None

    cur.execute(
        """
        SELECT block_index, payload
        FROM frame_blocks
        WHERE traj_uid = ?
        ORDER BY block_index
        """,
        (traj_uid,)
    )
    blocks = cur.fetchall()
    conn.close()

    if not blocks:
        raise ValueError(f"No frame blocks found for traj_uid='{traj_uid}'")

    os.makedirs(os.path.dirname(output_csv), exist_ok=True)

    frame_idx_global = 0
    with open(output_csv, "w", encoding="utf-8") as f:
        f.write("frame_idx,frame_number,energy,time_ps\n")

        for block_index, payload in blocks:
            coords_block, comments_block, energies_block = deserialize_block(payload)

            for comment, energy in zip(comments_block, energies_block):
                frame_number = extract_frame_number(comment)

                time_ps = None
                if frame_number is not None and timestep_fs is not None:
                    time_ps = frame_number * float(timestep_fs) / 1000.0

                energy_str = "" if energy is None else f"{energy:.10f}"
                time_str = "" if time_ps is None else f"{time_ps:.10f}"
                frame_number_str = "" if frame_number is None else str(frame_number)

                f.write(f"{frame_idx_global},{frame_number_str},{energy_str},{time_str}\n")
                frame_idx_global += 1

