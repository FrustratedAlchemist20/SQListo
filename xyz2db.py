def build_parser():
    parser = argparse.ArgumentParser(
        description="Guardar y recuperar trayectorias XYZ multiframa en SQLite comprimido."
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_store = sub.add_parser("store", help="Guardar un archivo XYZ en la base.")
    p_store.add_argument("xyz_file", help="Archivo XYZ multiframa de entrada")
    p_store.add_argument("db_file", help="Archivo SQLite de salida/uso")
    p_store.add_argument(
        "--block-size",
        type=int,
        default=500,
        help="Número de frames por bloque comprimido (por defecto: 500)"
    )
    p_store.add_argument(
        "--overwrite",
        action="store_true",
        help="Sobrescribe si ya existe esa trayectoria en la base"
    )

    p_restore = sub.add_parser("restore", help="Recuperar un XYZ desde la base.")
    p_restore.add_argument("db_file", help="Archivo SQLite")
    p_restore.add_argument("traj_uid", help="Identificador único de la trayectoria")
    p_restore.add_argument("output_xyz", help="Archivo XYZ de salida")

    p_list = sub.add_parser("list", help="Listar trayectorias guardadas.")
    p_list.add_argument("db_file", help="Archivo SQLite")

    p_restore_all = sub.add_parser("restore_all", help="Restore all XYZ trajectories from the database.")
    p_restore_all.add_argument("db_file", help="SQLite database file")
    p_restore_all.add_argument("output_dir", help="Output directory for restored XYZ files")

    p_store.add_argument("--input-file", default=None, help="Path to md.in input file")
    p_store.add_argument("--molecule", default=None, help="Molecule name, e.g. Triticonazole")
    p_store.add_argument("--isomer", default=None, help="Isomer label, e.g. E, Z, cis, trans")
    p_store.add_argument("--method", default=None, help="Method label, e.g. PM6, uB3LYP")
    p_store.add_argument("--energy-label", default=None, help="Energy label, e.g. ZPEx3")
    p_store.add_argument("--run-id", type=int, default=None, help="Trajectory/run number")

    return parser


def main():
    parser = build_parser()
    args = parser.parse_args()

    if args.command == "store":
        store_xyz_in_db(
            xyz_path=args.xyz_file,
            db_path=args.db_file,
           input_path=args.input_file,
            block_size=args.block_size,
            overwrite=args.overwrite,
            molecule=args.molecule,
            isomer=args.isomer,
            method=args.method,
            energy_label=args.energy_label,
            run_id=args.run_id,
        )
    elif args.command == "restore":
        restore_xyz_from_db(
            db_path=args.db_file,
            traj_uid=args.traj_uid,
            output_xyz=args.output_xyz
        )
    elif args.command == "list":
        list_trajectories(args.db_file)

    elif args.command == "restore_all":
        restore_all_from_db(
            db_path=args.db_file,
            output_dir=args.output_dir
        )
    else:
        parser.error("I cannot recognize the command.")

# Usage examples:
#
# 1) Store a multi-frame XYZ trajectory in a local SQLite database:
#    python xyz_sql_archive.py store coors.xyz central.db
#
# 2) Store a trajectory using a specific MD input file:
#    python xyz_sql_archive.py store coors.xyz central.db --input-file md.in
#
# 3) Store a trajectory with molecule/method/energy metadata:
#    python xyz_sql_archive.py store coors.xyz central.db --input-file md.in --molecule Azaconazole --method uB3LYP --energy-label ZPEx3
#
# 4) Store a trajectory including isomer and run number:
#    python xyz_sql_archive.py store coors.xyz central.db --input-file md.in --molecule Triticonazole --isomer E --method PM6 --energy-label ZPEx3 --run-id 1
#
# 5) Store a trajectory using larger compressed blocks:
#    python xyz_sql_archive.py store coors.xyz central.db --input-file md.in --block-size 1000
#
# 6) Overwrite an existing entry with the same file content:
#    python xyz_sql_archive.py store coors.xyz central.db --input-file md.in --overwrite
#
# 7) List all trajectories stored in the database:
#    python xyz_sql_archive.py list central.db
#
# 8) Restore a single trajectory from the database:
#    python xyz_sql_archive.py restore central.db TRAJ_UID restored_coors.xyz
#
# 9) Restore all stored trajectories into numbered folders:
#    python xyz_sql_archive.py restore-all central.db restored_runs
#
# 10) Example output layout for restore-all:
#     restored_runs/
#     ├── run_001/
#     │   └── coors.xyz
#     ├── run_002/
#     │   └── coors.xyz
#     ├── run_003/
#     │   └── coors.xyz
#
# Notes:
# - The script prevents exact duplicate trajectories by checking the SHA256 hash of the XYZ file.
# - MD input data from md.in is stored once and linked to the corresponding trajectories.
# - traj_uid is the internal unique trajectory identifier.
# - traj_code is a human-readable label built from molecule/isomer/method/energy/run metadata.
# - The database is local, portable, and does not require any external server.

