def make_input_id(input_path: str) -> tuple[str, str]:
    sha256_hex = sha256_file(input_path)
    short = hashlib.sha256(sha256_hex.encode("utf-8")).hexdigest()[:20]
    return f"inp_{short}", sha256_hex

def parse_md_input(input_path: str):
    data = {
        "input_filename": os.path.basename(input_path),
        "basis": None,
        "has_basis": 0,
        "coordinates_file": None,
        "charge": 0,
        "spinmult": 1,
        "method": None,
        "dispersion": None,
        "has_dispersion": 0,
        "run_type": None,
        "nstep": None,
        "timestep": None,
        "thermostat": None,
        "rescalefreq": None,
        "tinit": None,
        "t0": None,
        "gpus": None,
        "raw_input_text": None,
    }

    with open(input_path, "r", encoding="utf-8", errors="replace") as f:
        raw_text = f.read()

    data["raw_input_text"] = raw_text

    for raw_line in raw_text.splitlines():
        line = raw_line.strip()

        if not line or line.startswith("#"):
            continue

        parts = line.split(None, 1)
        key = parts[0].lower()
        value = parts[1].strip() if len(parts) > 1 else ""

        if key == "basis":
            data["basis"] = value
            data["has_basis"] = 1 if value else 0

        elif key == "coordinates":
            data["coordinates_file"] = value
        


        elif key == "charge":
            try:
                data["charge"] = int(value)
            except ValueError:
                data["charge"] = 0

        elif key in ("spinmult", "multiplicity"):
            try:
                value_int = int(value)
                data["spinmult"] = max(1, value_int)
            except ValueError:
                data["spinmult"] = 1

        elif key == "method":
            data["method"] = value

        elif key == "dispersion":
            data["dispersion"] = value
            data["has_dispersion"] = 1 if value.lower() not in ("", "no", "none", "false", "0") else 0

        elif key == "run":
            data["run_type"] = value

        elif key == "nstep":
            try:
                data["nstep"] = int(value)
            except ValueError:
                data["nstep"] = value

        elif key == "timestep":
            try:
                data["timestep"] = float(value)
            except ValueError:
                data["timestep"] = value

        elif key == "thermostat":
            data["thermostat"] = value

        elif key == "rescalefreq":
            try:
                data["rescalefreq"] = int(value)
            except ValueError:
                data["rescalefreq"] = value

        elif key == "tinit":
            try:
                data["tinit"] = float(value)
            except ValueError:
                data["tinit"] = value

        elif key == "t0":
            try:
                data["t0"] = float(value)
            except ValueError:
                data["t0"] = value

        elif key == "gpus":
            try:
                data["gpus"] = int(value)
            except ValueError:
                data["gpus"] = value

    return data


def store_md_input(conn, input_path: str):
    input_path = os.path.abspath(input_path)
