def parse_xyz_multiframe(filepath: str):
    """
    Lee un .xyz multiframa completo.

    Devuelve:
      natoms: int
      symbols: list[str]
      frames_coords: np.ndarray shape (nframes, natoms, 3)
      comments: list[str]
      energies: list[float|None]
    """
    frames_coords = []
    comments = []
    energies = []
    symbols_ref = None
    natoms_ref = None

    with open(filepath, "r", encoding="utf-8", errors="replace") as f:
        lines = f.readlines()

    i = 0
    frame_idx = 0
    nlines = len(lines)

    while i < nlines:
        line = lines[i].strip()
        if not line:
            i += 1
            continue

        try:
            natoms = int(line)
        except ValueError as exc:
            raise ValueError(
                f"Formato XYZ inválido en la línea {i+1}: se esperaba número de átomos."
            ) from exc

        if i + 1 >= nlines:
            raise ValueError(f"Frame incompleto en línea {i+1}: falta la línea de comentario.")

        comment = lines[i + 1].rstrip("\n")
        energies.append(extract_energy(comment))
        comments.append(comment)

        block_start = i + 2
        block_end = block_start + natoms
        if block_end > nlines:
            raise ValueError(f"Frame incompleto en frame {frame_idx}: faltan líneas atómicas.")

        frame_symbols = []
        frame_coords = np.zeros((natoms, 3), dtype=np.float32)

        for j, raw in enumerate(lines[block_start:block_end]):
            parts = raw.split()
            if len(parts) < 4:
                raise ValueError(
                    f"Línea atómica inválida en frame {frame_idx}, línea {block_start + j + 1}."
                )
            sym = parts[0]
            if sym not in SYMBOL_TO_Z:
                raise ValueError(f"Símbolo atómico no reconocido: '{sym}'")
            try:
                x, y, z = map(float, parts[1:4])
            except ValueError as exc:
                raise ValueError(
                    f"Coordenadas inválidas en frame {frame_idx}, línea {block_start + j + 1}."
                ) from exc

            frame_symbols.append(sym)
            frame_coords[j] = [x, y, z]

        if natoms_ref is None:
            natoms_ref = natoms
            symbols_ref = frame_symbols
        else:
            if natoms != natoms_ref:
                raise ValueError(
                    f"El número de átomos cambia entre frames: {natoms_ref} vs {natoms}"
                )
            if frame_symbols != symbols_ref:
                raise ValueError(
                    "El orden o identidad de los átomos cambia entre frames. "
                    "Este script asume topología/orden atómico fijo."
                )

        frames_coords.append(frame_coords)
        i = block_end
        frame_idx += 1

    if natoms_ref is None or not frames_coords:
        raise ValueError("No se encontraron frames válidos en el archivo XYZ.")

    frames_coords = np.stack(frames_coords, axis=0)
    return natoms_ref, symbols_ref, frames_coords, comments, energies


