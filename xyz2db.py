def sha256_file(filepath: str, chunk_size: int = 1024 * 1024) -> str:
    h = hashlib.sha256()
    with open(filepath, "rb") as f:
        while True:
            chunk = f.read(chunk_size)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def make_traj_uid(filepath: str, sha256_hex: str) -> str:
    base = f"{Path(filepath).name}|{sha256_hex}"
    uid = hashlib.sha256(base.encode("utf-8")).hexdigest()[:24]
    return f"traj_{uid}"

def extract_frame_number(comment: str):
    """
    Extract frame number from lines like:
      -1698.99738 frame 9004   xyz file generated by terachem
    """
    m = re.search(r'(?i)\bframe\s+(\d+)\b', comment)
    if m:
        try:
            return int(m.group(1))
        except ValueError:
            return None
    return None

def extract_energy(comment: str):
    """
    Intenta extraer una energía de la segunda línea.

    Casos soportados:
      E=-123.456
      energy = -123.456
      Energy: -123.456
      -1698.99738 frame 9004   xyz file generated by terachem
    """
    patterns = [
        r'(?i)\bE(?:nergy)?\s*[:=]\s*([-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)',
        r'(?i)\bEtot\s*[:=]\s*([-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)',
        r'^\s*([-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)\b',  # número al principio de la línea
    ]
    for pat in patterns:
        m = re.search(pat, comment)
        if m:
            try:
                return float(m.group(1))
            except ValueError:
                return None
    return None


def serialize_block(coords_block: np.ndarray, comments_block, energies_block):
    """
    Empaqueta un bloque en bytes comprimidos.
    """
    bio = BytesIO()
    np.savez(
        bio,
        coords=coords_block.astype(np.float32),
        comments=np.array(comments_block, dtype=object),
        energies=np.array(
            [np.nan if e is None else e for e in energies_block],
            dtype=np.float64
        )
    )
    raw = bio.getvalue()
    return lzma.compress(raw, preset=6)


def deserialize_block(blob: bytes):
    raw = lzma.decompress(blob)
    bio = BytesIO(raw)
    data = np.load(bio, allow_pickle=True)
    coords = data["coords"]
    comments = data["comments"].tolist()
    energies = data["energies"]
    energies = [None if np.isnan(x) else float(x) for x in energies]
    return coords, comments, energies


